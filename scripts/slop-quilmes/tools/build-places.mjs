// Shops, landmarks and stations of the GTA Quilmes map in the simulation's grid frame -> js/quilmes-places.js
// usage: node tools/build-places.mjs <path to public/data/quilmes.json>
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { toWorld, log } from './geo-base.mjs';
import path from 'node:path';

const game = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const { lat: LAT0, lon: LON0 } = game.origin;
// the game's frame: x east, z south, metres from its origin (local tangent plane)
const A = 6378137.0, E2 = 6.69437999014e-3;
const PHI0 = (LAT0 * Math.PI) / 180, S0 = Math.sin(PHI0);
const KX = (Math.PI / 180) * (A / Math.sqrt(1 - E2 * S0 * S0)) * Math.cos(PHI0);
const KY = (Math.PI / 180) * ((A * (1 - E2)) / Math.pow(1 - E2 * S0 * S0, 1.5));
// game metres -> lon/lat exactly as prepare.py does (local tangent plane through ECEF)
const lo0 = (LON0 * Math.PI) / 180, la0 = (LAT0 * Math.PI) / 180;
const N0 = A / Math.sqrt(1 - E2 * Math.sin(la0) ** 2);
const X0 = N0 * Math.cos(la0) * Math.cos(lo0), Y0 = N0 * Math.cos(la0) * Math.sin(lo0), Z0 = N0 * (1 - E2) * Math.sin(la0);
const [sl, cl, sp, cp] = [Math.sin(lo0), Math.cos(lo0), Math.sin(la0), Math.cos(la0)];
function lonLat(x, z) {
  const e = x, n = -z;
  const X = X0 - sl * e - sp * cl * n, Y = Y0 + cl * e - sp * sl * n, Z = Z0 + cp * n;
  const p = Math.hypot(X, Y);
  let lat = Math.atan2(Z, p * (1 - E2));
  for (let i = 0; i < 6; i++) {
    const N = A / Math.sqrt(1 - E2 * Math.sin(lat) ** 2);
    lat = Math.atan2(Z + E2 * N * Math.sin(lat), p);
  }
  return [(Math.atan2(Y, X) * 180) / Math.PI, (lat * 180) / Math.PI];
}
const gridExact = (x, z) => toWorld(...lonLat(x, z));
const grid = (x, z) => gridExact(x, z).map((v) => Math.round(v * 10) / 10);
// the game's frame as one rigid turn + offset (for the hand-made places): least squares over the map
let theta = 0, ox = 0, oz = 0, resid = 0;
{
  const P = [];
  for (let x = -4400; x <= 5700; x += 400) for (let z = -3800; z <= 6300; z += 400) P.push([x, z, ...gridExact(x, z)]);
  const n = P.length;
  const mx = P.reduce((t, p) => t + p[0], 0) / n, mz = P.reduce((t, p) => t + p[1], 0) / n;
  const gx = P.reduce((t, p) => t + p[2], 0) / n, gz = P.reduce((t, p) => t + p[3], 0) / n;
  let sxx = 0, sxz = 0;
  for (const [x, z, u, v] of P) {
    const a = x - mx, b = z - mz, c = u - gx, d = v - gz;
    sxx += a * c + b * d; // grid = R(theta) game: u = x cos + z sin, v = -x sin + z cos
    sxz += b * c - a * d;
  }
  theta = Math.atan2(sxz, sxx);
  const c = Math.cos(theta), s = Math.sin(theta);
  ox = gx - (mx * c + mz * s);
  oz = gz - (-mx * s + mz * c);
  for (const [x, z, u, v] of P) resid = Math.max(resid, Math.hypot(x * c + z * s + ox - u, -x * s + z * c + oz - v));
}
// exact enough for facades: a quadratic in (x, z) / 1000 per grid coordinate, least squares
const basis = (x, z) => { const a = x / 1000, b = z / 1000; return [1, a, b, a * a, a * b, b * b]; };
function fit(k) {
  const N = 6, M = Array.from({ length: N }, () => new Array(N + 1).fill(0));
  for (let x = -4600; x <= 5900; x += 150) for (let z = -4000; z <= 6500; z += 150) {
    const f = basis(x, z), g = gridExact(x, z)[k];
    for (let i = 0; i < N; i++) { for (let j = 0; j < N; j++) M[i][j] += f[i] * f[j]; M[i][N] += f[i] * g; }
  }
  for (let i = 0; i < N; i++) { // Gauss-Jordan
    let piv = i;
    for (let r = i + 1; r < N; r++) if (Math.abs(M[r][i]) > Math.abs(M[piv][i])) piv = r;
    [M[i], M[piv]] = [M[piv], M[i]];
    for (let r = 0; r < N; r++) if (r !== i) { const f = M[r][i] / M[i][i]; for (let c = i; c <= N; c++) M[r][c] -= f * M[i][c]; }
  }
  return M.map((row, i) => row[N] / row[i]);
}
const polyU = fit(0), polyV = fit(1);
let presid = 0;
for (let x = -4400; x <= 5700; x += 97) for (let z = -3800; z <= 6300; z += 97) {
  const f = basis(x, z), [u, v] = gridExact(x, z);
  presid = Math.max(presid, Math.hypot(f.reduce((t, c, i) => t + c * polyU[i], 0) - u, f.reduce((t, c, i) => t + c * polyV[i], 0) - v));
}
log(`game frame -> grid, quadratic: max error ${presid.toFixed(3)} m`);
log(`game frame -> grid: theta ${(theta * 180 / Math.PI).toFixed(4)}°, offset ${ox.toFixed(2)}, ${oz.toFixed(2)}, max error ${resid.toFixed(2)} m`);

const shops = game.shops.filter((s) => s.name).map((s) => [s.name, s.kind || '', ...grid(s.x, s.z)]);
const landmarks = game.landmarks.map((l) => [l.name, ...grid(l.pos[0], l.pos[1])]);
const stations = game.specials.filter((s) => s.type === 'station' && s.name).map((s) => [s.name, ...grid(s.cx, s.cz)]);
const out = fileURLToPath(new URL('../js/quilmes-places.js', import.meta.url));
fs.writeFileSync(out, `// js/quilmes-places.js — GENERATED by tools/build-places.mjs from the GTA Quilmes map, do not edit by hand.
// Grid frame metres. Sources: © OpenStreetMap contributors (ODbL), Overture Maps Foundation.
// [name, kind, x, z]
export const SHOPS = ${JSON.stringify(shops)};
// [name, x, z]
export const LANDMARKS = ${JSON.stringify(landmarks)};
export const STATIONS = ${JSON.stringify(stations)};
// game metres -> grid: grid = R(theta) * game + (x, z), theta about +y (rigid, within ~3 m); exact (cm): u, v are\n// quadratics in (x / 1000, z / 1000): [1, x, z, x², xz, z²]
export const GAME_FRAME = ${JSON.stringify({ theta, x: ox, z: oz, u: polyU, v: polyV })};
`);
const shopCells = new Map();
for (const s of game.shops) {
  const k = `${Math.floor(s.x / 40)},${Math.floor(s.z / 40)}`;
  if (!shopCells.has(k)) shopCells.set(k, []);
  shopCells.get(k).push(s);
}
// what the game's landmarks.js / zones.js / shops.js read
const world = {
  roads: game.roads, specials: game.specials, shops: game.shops,
  rails: game.rails, decks: game.decks, levelCrossings: game.levelCrossings,
  // colectivo lines and stops (paradas, metrobus stations)
  buses: JSON.parse(fs.readFileSync(path.join(path.dirname(process.argv[2]), 'buses.json'), 'utf8')),
  // the landmarks' buildings, and the ones a shop may hang its front on
  buildings: game.buildings.filter((b) => {
    if (b.special) return true;
    const [x, z] = b.pts[0];
    for (let a = -1; a <= 1; a++) for (let c = -1; c <= 1; c++) {
      for (const s of shopCells.get(`${Math.floor(x / 40) + a},${Math.floor(z / 40) + c}`) || []) if (Math.hypot(s.x - x, s.z - z) < 45) return true;
    }
    return false;
  }).map((b) => ({ pts: b.pts, h: b.h, levels: b.levels, special: b.special, name: b.name, style: b.style, shop: b.shop })),
  bounds: game.bounds,
};
const wout = path.join(path.dirname(out), 'gta-world.json');
fs.writeFileSync(wout, JSON.stringify(world));
log(`wrote ${wout} (${(fs.statSync(wout).size / 1024).toFixed(0)} KB)`);
// The houses the game draws itself (gtaWorld.js buildHouses): low houses and the villas, carried into the grid
// frame here (exact mapping) so the game's generator runs there directly. Compact: per building
// [h * 10, levels, style, front (-1 none), shop, villa, gable, x0, z0 (dm), then dx, dz (dm) of the next points].
const polyAt = (x, z) => { const f = basis(x, z); return [f.reduce((t, c, i) => t + c * polyU[i], 0), f.reduce((t, c, i) => t + c * polyV[i], 0)]; };
const STYLES = ['house', 'brick', 'villa', 'apartments', 'industrial', 'office', 'school', 'hospital', 'brewery', 'civic', 'church', 'ph', 'mall', 'station', 'monument'];
const stands = game.specials.filter((sp) => sp.type === 'stadium').map((sp) => [sp.box, 3 + Math.max(sp.depth || 0, 12)]);
const underStand = (x, z) => stands.some(([o, r]) => {
  const dx = x - o.cx, dz = z - o.cz;
  return Math.abs(dx * o.ux + dz * o.uz) < o.hu + r && Math.abs(dx * o.vx + dz * o.vz) < o.hv + r;
});
export const gameHouse = (b) => !b.special && (b.villa || ((b.style === 'house' || b.style === 'brick') && b.h < 10.5));
const houses = [];
for (const b of game.buildings) {
  if (!gameHouse(b) || b.pts.length < 3 || underStand(b.pts[0][0], b.pts[0][1])) continue;
  const g = b.pts.map(([x, z]) => polyAt(x, z).map((v) => Math.round(v * 10)));
  const row = [Math.round(b.h * 10), b.levels || 1, Math.max(0, STYLES.indexOf(b.style)), b.front ?? -1, b.shop ? 1 : 0, b.villa ? 1 : 0, b.roof === 'gable' ? 1 : 0, g[0][0], g[0][1]];
  for (let i = 1; i < g.length; i++) row.push(g[i][0] - g[i - 1][0], g[i][1] - g[i - 1][1]);
  houses.push(row);
}
const roadsGrid = game.roads.map((r) => ({ ...r, pts: r.pts.map(([x, z]) => polyAt(x, z).map((v) => Math.round(v * 100) / 100)) }));
const hout = path.join(path.dirname(out), 'gta-houses.json');
// street corner signs (posts and the direction of each plate) in the grid frame too
const [tc, ts] = [Math.cos(theta), Math.sin(theta)];
const streetSigns = (game.streetSigns || []).map((p) => {
  const [x, z] = polyAt(p.x, p.z);
  return { x: Math.round(x * 100) / 100, z: Math.round(z * 100) / 100, signs: p.signs.map((sg) => ({ ...sg, dir: [sg.dir[0] * tc + sg.dir[1] * ts, -sg.dir[0] * ts + sg.dir[1] * tc].map((v) => Math.round(v * 1000) / 1000) })) };
});
// the conurbano layer (conurbano.js): property-line fences, villas, descampados (their cells stay in the game's
// grid, mapped at build time), scrub / wetland areas
const r2 = (v) => Math.round(v * 100) / 100;
const fences = [];
for (let i = 0; i < game.fences.length; i += 5) {
  const a = polyAt(game.fences[i], game.fences[i + 1]), b = polyAt(game.fences[i + 2], game.fences[i + 3]);
  fences.push(r2(a[0]), r2(a[1]), r2(b[0]), r2(b[1]), game.fences[i + 4]);
}
const wastes = game.wastes.map((w) => (w.potrero ? { ...w, potrero: { c: polyAt(...w.potrero.c).map(r2), a: w.potrero.a - theta } } : w));
const areas = game.areas.filter((a) => ['scrub', 'waste', 'wetland'].includes(a.kind)).map((a) => ({ kind: a.kind, pts: a.pts.map(([x, z]) => polyAt(x, z).map(r2)) }));
fs.writeFileSync(hout, JSON.stringify({ styles: STYLES, houses, roads: roadsGrid, streetSigns, conurbano: { grid: game.grid, villas: game.villas, wastes, fences, fenceTypes: game.fenceTypes, areas } }));
log(`wrote ${hout}: ${houses.length} houses (${(fs.statSync(hout).size / 1024).toFixed(0)} KB)`);
// colectivo lines for the engine's traffic (traffic.js): the route polylines in the grid frame with the distance
// along them of every stop
const busData = JSON.parse(fs.readFileSync(path.join(path.dirname(process.argv[2]), 'buses.json'), 'utf8'));
const busRoutes = busData.routes.filter((r) => r.path.length > 1).map((r) => {
  const pts = r.path.map(([x, z]) => polyAt(x, z).map((v) => Math.round(v * 10) / 10));
  const k = pts.length > 1 ? 1 : 1;
  return { line: r.line, dest: (r.headsign || r.name || '').replace(/^[A-Z] - /, ''), pts: pts.flat(), stops: (r.stops || []).map((st) => Math.round(st.s * k)) };
});
const bout = path.join(path.dirname(out), 'quilmes-buses.js');
fs.writeFileSync(bout, `// js/quilmes-buses.js — GENERATED by tools/build-places.mjs from the AMBA GTFS lines of GTA Quilmes, do not edit.
// Grid frame: pts flat [x, z, ...], stops = metres along the route.
export const BUS_ROUTES = ${JSON.stringify(busRoutes)};
`);
log(`wrote ${bout}: ${busRoutes.length} routes (${(fs.statSync(bout).size / 1024).toFixed(0)} KB)`);
log(`wrote ${out}: ${shops.length} shops, ${landmarks.length} landmarks, ${stations.length} stations`);
